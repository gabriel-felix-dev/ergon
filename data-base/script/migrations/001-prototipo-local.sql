-- Executar uma vez em uma cópia local do banco criado pela versão anterior.
-- Antes da execução, conferir emails duplicados por assistência; o índice único
-- de Cliente falhará se houver duplicatas que precisam ser resolvidas.
BEGIN;

ALTER TABLE public."Funcionario"
    ALTER COLUMN "Nome" DROP NOT NULL,
    ALTER COLUMN "Documento" DROP NOT NULL,
    ALTER COLUMN "SenhaHash" DROP NOT NULL,
    ADD COLUMN "VersaoSessao" INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public."Cliente"
    ADD COLUMN "SenhaHash" VARCHAR(255),
    ADD COLUMN "VersaoSessao" INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public."Aparelho"
    ADD COLUMN "Ativo" BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE public."OrdemServico"
    DROP CONSTRAINT "CK_OrdemServico_Status",
    ADD CONSTRAINT "CK_OrdemServico_Status" CHECK ("Status" IN (
        'AguardandoAparelho', 'AguardandoReparo', 'EmReparo', 'ReparoConcluido',
        'Paga', 'Cancelada', 'Desistencia'
    ));

ALTER TABLE public."Pagamento"
    ADD COLUMN "RegistradoEm" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE public."ConviteFuncionario" (
    "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdAssistenciaTecnica" INTEGER NOT NULL,
    "IdFuncionario" INTEGER NOT NULL,
    "TokenHash" CHAR(64) NOT NULL UNIQUE,
    "ExpiraEm" TIMESTAMPTZ NOT NULL,
    "UsadoEm" TIMESTAMPTZ,
    FOREIGN KEY ("IdFuncionario", "IdAssistenciaTecnica")
        REFERENCES public."Funcionario" ("Id", "IdAssistenciaTecnica")
);

CREATE TABLE public."RecuperacaoSenha" (
    "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdAssistenciaTecnica" INTEGER NOT NULL,
    "IdFuncionario" INTEGER,
    "IdCliente" INTEGER,
    "CodigoHash" CHAR(64) NOT NULL,
    "CriadoEm" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ExpiraEm" TIMESTAMPTZ NOT NULL,
    "UsadoEm" TIMESTAMPTZ,
    "Tentativas" INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT "CK_RecuperacaoSenha_Titular" CHECK (
        ("IdFuncionario" IS NOT NULL AND "IdCliente" IS NULL) OR
        ("IdFuncionario" IS NULL AND "IdCliente" IS NOT NULL)
    ),
    FOREIGN KEY ("IdFuncionario", "IdAssistenciaTecnica")
        REFERENCES public."Funcionario" ("Id", "IdAssistenciaTecnica"),
    FOREIGN KEY ("IdCliente", "IdAssistenciaTecnica")
        REFERENCES public."Cliente" ("Id", "IdAssistenciaTecnica")
);

CREATE UNIQUE INDEX "UQ_Cliente_Assistencia_Email"
    ON public."Cliente" ("IdAssistenciaTecnica", LOWER("Email"));
CREATE INDEX "IX_ConviteFuncionario_ExpiraEm"
    ON public."ConviteFuncionario" ("ExpiraEm");
CREATE INDEX "IX_RecuperacaoSenha_ExpiraEm"
    ON public."RecuperacaoSenha" ("ExpiraEm");

DROP TABLE public."SessaoAcesso";
COMMIT;
